"""Deterministic, multilingual decision-letter rendering.

The letter is generated by templating (never by an LLM) from the frozen fields of a
``DecisionLetter`` row: applicant ID, decision date, outcome, the same reason codes the
model produced, the model version, and (once signed) the officer's identity. Because the
reasons come straight from the glass-box model's own reason codes, the letter cannot
disagree with the decision it explains.

Rendering is server-side so the letter is a self-contained, reproducible document in the
borrower's chosen language (English / Hindi / Bengali), not something reassembled by the
frontend. Reason phrases drawn from the model's fixed vocabulary are translated; any
dynamically-composed qualifier (thin-file, consent-withdrawal, panel disagreement) falls
back to its stored English text.
"""

