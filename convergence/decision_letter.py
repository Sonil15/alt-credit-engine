def _normalise_lang(lang: str | None) -> str:
    return lang if lang in SUPPORTED_LANGUAGES else "en"


def _translate_reason(label: str, lang: str) -> str:
    if lang == "en":
        return label
    return REASON_I18N.get(label, {}).get(lang, label)


def _outcome_kind(outcome: str) -> str:
    """Map any decision string onto one of approve / review / reject."""
    value = (outcome or "").upper()
    if value == "APPROVE":
        return "approve"
    if value == "REJECT":
        return "reject"
    return "review"


def render_letter(letter: dict[str, Any], lang: str | None = "en") -> dict[str, Any]:
    """Render a frozen letter record into a structured, translated document.

    ``letter`` carries the persisted fields: ``user_id``, ``status``, ``outcome``,
    ``credit_score``, ``model_version``, ``reason_codes`` (list of English labels),
    ``created_at``, and optionally ``officer_id`` / ``signed_at``.
    """
    lang = _normalise_lang(lang)
    strings = LETTER_I18N[lang]
    kind = _outcome_kind(letter.get("outcome", "REVIEW"))

    reasons = [_translate_reason(r, lang) for r in (letter.get("reason_codes") or [])]

    created = letter.get("created_at")
    date_str = format_human_date(created.date(), lang) if isinstance(created, datetime) else str(created or "")
    signed = letter.get("signed_at")
    signed_str = format_human_date(signed.date(), lang) if isinstance(signed, datetime) else (str(signed) if signed else None)

    user_id = str(letter.get("user_id", ""))
    ref = "AC-" + datetime.now(timezone.utc).strftime("%Y") + "-" + user_id.replace("-", "")[:8].upper()

    body = {
        "title": strings[f"title_{kind}"],
        "subtitle": strings["subtitle"],
        "ref_label": strings["ref_label"],
        "ref": ref,
        "date_label": strings["date_label"],
        "date": date_str,
        "applicant_label": strings["applicant_label"],
        "applicant_id": (user_id[:8] + "··· (masked)") if user_id else "—",
        "outcome_label": strings["outcome_label"],
        "outcome_text": strings[f"outcome_{kind}"],
        "model_label": strings["model_label"],
        "model_version": str(letter.get("model_version", "")),
        "body_text": strings[f"body_{kind}"],
        "reasons_heading": strings["reasons_heading"],
        "reasons": reasons or [strings["no_reasons"]],
        "rights": strings["rights"],
        "grievance": strings["grievance"],
        "signed_by_label": strings["signed_by"],
        "signed_on_label": strings["signed_on"],
    }

    status = letter.get("status", "pending_review")
    if status == "pending_review":
        body["status_note"] = strings["pending_note"]
        body["officer"] = strings["officer_pending"]
    elif letter.get("officer_id"):
        body["officer"] = letter["officer_id"]
        body["signed_on"] = signed_str
    else:
        body["status_note"] = strings["auto_note"]

    return {
        "user_id": user_id,
        "status": status,
        "outcome": letter.get("outcome"),
        "language": lang,
        "letter": body,
        "plain_text": _to_plain_text(body, status),
    }


def _to_plain_text(body: dict[str, Any], status: str) -> str:
    """A downloadable plain-text rendering of the letter."""
    lines = [
        body["title"].upper(),
        body["subtitle"],
        "",
        f"{body['ref_label']}: {body['ref']}",
        f"{body['date_label']}: {body['date']}",
        f"{body['applicant_label']}: {body['applicant_id']}",
        f"{body['outcome_label']}: {body['outcome_text']}",
        f"{body['model_label']}: {body['model_version']}",
        "",
        body["body_text"],
        "",
        body["reasons_heading"] + ":",
    ]
    lines += [f"  {i}. {r}" for i, r in enumerate(body["reasons"], start=1)]
    lines += ["", body["rights"], "", body["grievance"], ""]
    if body.get("officer") and status == "issued" and body.get("signed_on"):
        lines.append(f"{body['signed_by_label']}: {body['officer']} ({body['signed_on_label']}: {body['signed_on']})")
    elif body.get("status_note"):
        lines.append(body["status_note"])
    return "\n".join(lines)
