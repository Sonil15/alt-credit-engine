const STORAGE_LANG_KEY = 'altcredit_lang';

function getCurrentLanguage() {
  return localStorage.getItem(STORAGE_LANG_KEY) || 'en';
}

function setCurrentLanguage(lang) {
  localStorage.setItem(STORAGE_LANG_KEY, lang);
  // Also try to dispatch a custom event so other elements/listeners know
  window.dispatchEvent(new CustomEvent('altcreditLanguageChanged', { detail: lang }));
}

function translatePage(lang = getCurrentLanguage()) {
  document.documentElement.setAttribute('lang', lang);
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (ALTCREDIT_DICTIONARY[lang] && ALTCREDIT_DICTIONARY[lang][key]) {
      const val = ALTCREDIT_DICTIONARY[lang][key];
      // Handle placeholder translation if it's an input
      if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
        el.setAttribute('placeholder', val);
      } else {
        el.textContent = val;
      }
    }
  });

  // Highlight the active language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

function setupLanguageSelector(containerId) {
  const container = document.getElementById(containerId);
  if (!container) return;

  container.innerHTML = `
    <div class="lang-selector">
      <button class="lang-btn" data-lang="en" title="English">English</button>
      <button class="lang-btn" data-lang="hi" title="हिन्दी">हिन्दी</button>
      <button class="lang-btn" data-lang="bn" title="বাংলা">বাংলা</button>
    </div>
  `;

  // Attach click events
  container.querySelectorAll('.lang-btn').forEach(btn => {
    btn.onclick = (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      setCurrentLanguage(lang);
      translatePage(lang);
    };
  });

  // Call once to set active state
  translatePage();
}

// Auto-run if DOM loaded
document.addEventListener('DOMContentLoaded', () => {
  translatePage();
});
